"""Verify paired control measurements and generate non-floating LaTeX tables."""

import json
import math
from pathlib import Path
from statistics import fmean, pstdev


ROOT = Path(__file__).resolve().parent
DATA = ROOT / "results" / "controls"


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def check_stats(values, recorded):
    assert len(values) == 5, "Every attribution row must contain five seeds."
    for key, value in (("mean", fmean(values)), ("std", pstdev(values))):
        assert math.isclose(value, recorded[key], abs_tol=1e-10), (key, value, recorded)
    assert recorded["positive_seeds"] == sum(x > 0 for x in values)
    assert all(math.isclose(a, b, abs_tol=1e-10)
               for a, b in zip(values, recorded["per_seed"]))


def verify(attribution, configs, latency):
    assert attribution["protocol"]["seeds"] == list(range(5))
    for name, baseline, target in (
        ("seqtxglobal64_vs_seqtxcount", "SeqTXCount", "SeqTXGlobal"),
        ("twotower_ensmix_vs_ensmean", "TwoTowerEnsMean", "TwoTowerEnsMix"),
    ):
        for scope, metrics in attribution[name].items():
            for metric, recorded in metrics.items():
                values = []
                for cfg in configs:
                    rows = cfg["metrics"] if scope == "full" else cfg["tail_slices"][scope]["metrics"]
                    gain = rows[target][metric] - rows[baseline][metric]
                    values.append(gain if metric == "utility" else -gain)
                check_stats(values, recorded)
    for target, budgets in attribution["routing"].items():
        for budget, selectors in budgets.items():
            for selector in ("TaxScore", "CheapUncertainty", "Random"):
                for metric, recorded in selectors[selector].items():
                    values = []
                    for cfg in configs:
                        value = cfg["matched_routing_attribution"]["targets"][target][budget][selector][metric]
                        values.append(value["mean"] if selector == "Random" else value)
                    check_stats(values, recorded)
            for comparator in ("CheapUncertainty", "Random"):
                for metric in ("full_nll_gain", "full_utility_gain"):
                    vals = [a - b for a, b in zip(
                        selectors["TaxScore"][metric]["per_seed"],
                        selectors[comparator][metric]["per_seed"])]
                    check_stats(vals, selectors["TaxScore_minus_" + comparator][metric])
                    assert min(vals) > 0, "A claimed five-seed advantage fails."
    for cfg in configs:
        assert cfg["config"]["test_samples"] == 1652
        assert cfg["config"]["taxscore_grid_size"] == 16
        assert cfg["config"]["seqtxglobal_components"] == 64
    for model, batches in latency["model_ranges"].items():
        for batch, recorded in batches.items():
            actual = [read(DATA / run["file"])["models"][model][batch]["mean_ms_per_slate"]
                      for run in latency["clean_runs"]]
            assert math.isclose(min(actual), recorded["min"], abs_tol=1e-12)
            assert math.isclose(max(actual), recorded["max"], abs_tol=1e-12)


def stat(row, digits=4):
    return "$" + rf"{row['mean']:.{digits}f}\pm{row['std']:.{digits}f}" + "$"


def interval(row, digits):
    return "$" + f"{row['min']:.{digits}f}" + "$--$" + f"{row['max']:.{digits}f}" + "$"


def table(label, caption, header, rows, columns):
    return "\n".join([
        r"\begin{paperblock}", r"\begin{minipage}{0.985\linewidth}",
        rf"\captionof{{table}}{{{caption}}}", rf"\label{{{label}}}",
        r"\centering\footnotesize", r"\setlength{\tabcolsep}{4pt}",
        r"\renewcommand{\arraystretch}{1.08}",
        rf"\begin{{tabular}}{{@{{}}{columns}@{{}}}}", r"\toprule",
        header + r" \\", r"\midrule",
        *[row + r" \\" for row in rows],
        r"\bottomrule", r"\end{tabular}", r"\end{minipage}", r"\end{paperblock}", "",
    ])


def main():
    a = read(DATA / "attribution_summary.json")
    configs = [read(DATA / f"attr_seed{s}.json")["configs"]["crit80"] for s in range(5)]
    latency = read(DATA / "l20_latency_clean_summary.json")
    aggregate = ROOT / "aggregate_results.json"
    if not aggregate.exists():
        aggregate = ROOT / "results/aggregate_results.json"
    original = read(aggregate)
    verify(a, configs, latency)
    (ROOT / "figures").mkdir(exist_ok=True)
    blocks = ["% Generated by make_control_tables.py from verified archived measurements.\n"]
    rows = []
    for scope, label in (("full", "Full population"), ("top20", r"Top 20\%")):
        row = a["seqtxglobal64_vs_seqtxcount"][scope]
        rows.append(f"{label} & {stat(row['nll'])} & {stat(row['utility'])}"
                    f" & {row['nll']['positive_seeds']}/5, {row['utility']['positive_seeds']}/5")
    blocks.append(table(
        "tab:matched-attribution",
        r"Same-backbone ML1M-80 control: SeqTXGlobal-64 relative to SeqTXCount. "
        r"Entries are mean $\pm$ population standard deviation of paired differences over five seeds. "
        r"Positive NLL reduction and utility gain favor the latent head. The backbone is fixed, "
        r"but the output heads differ in parameter count. 64 components match latent-evaluation resolution while runtime can differ.",
        "Population & NLL reduction & Utility gain & Positive seeds (NLL, util.)",
        rows, "lccc"))
    rows = []
    for scope, label in (("full", "Full population"), ("top20", r"Top 20\%")):
        row = a["twotower_ensmix_vs_ensmean"][scope]
        rows.append(" & ".join([label, stat(row["nll"]), stat(row["brier"], 5),
                               stat(row["ece"], 5), stat(row["utility"])]))
    blocks.append(table(
        "tab:ensemble-attribution",
        r"Fixed-member averaging control: TwoTowerEnsMix relative to TwoTowerEnsMean on ML1M-80. "
        r"The same three trained members (72,579 parameters) and predictions are reused. "
        r"Only tail aggregation changes. NLL/Brier/ECE reductions are positive in all five seeds. "
        r"Utility decreases slightly despite the consistently improved probability estimates on the same evaluation groups.",
        "Population & NLL reduction & Brier reduction & ECE reduction & Utility change",
        rows, "lcccc"))
    rows = []
    for target, budgets in a["routing"].items():
        for budget, selectors in budgets.items():
            for selector in ("TaxScore", "CheapUncertainty", "Random"):
                row = selectors[selector]
                name = "Cheap uncertainty" if selector == "CheapUncertainty" else selector
                rows.append(" & ".join([target, budget.replace("%", r"\%"), name,
                                       stat(row["full_nll_gain"]), stat(row["full_utility_gain"])]))
    blocks.append(table(
        "tab:matched-routing",
        r"Equal-budget ML1M-80 routing: full-population improvements over SeqTXCount, "
        r"with five-seed mean $\pm$ standard deviation. All selectors route exactly 330/1,652 "
        r"or 496/1,652 test slates. Random rows average 100 masks within each seed. "
        r"Cheap uncertainty is $p(1-p)$. Each mixed-policy confidence threshold is selected on validation users. "
        r"TaxScore exceeds each comparator for both metrics in all five seeds at each head/budget setting. "
        r"These estimates use exact budgets. The original switch instead transfers a validation cutoff with a variable achieved fraction.",
        "Rich head & Budget & Selector & NLL reduction & Utility gain", rows, "lllcc"))
    main_rows = []
    for target, budgets in a["routing"].items():
        for budget, selectors in budgets.items():
            cells = [target + " / " + budget.replace("%", r"\%")]
            for selector in ("TaxScore", "CheapUncertainty", "Random"):
                row = selectors[selector]
                cells.append(f"{row['full_nll_gain']['mean']:.4f} / "
                             f"{row['full_utility_gain']['mean']:.4f}")
            main_rows.append(" & ".join(cells))
    routing_main = table(
        "tab:routing-main",
        r"Equal-budget routing on ML1M-80. Each cell reports full-population NLL reduction / "
        r"utility gain over SeqTXCount (five-seed means). All selectors route the same number "
        r"of test slates. Appendix Table~\ref{tab:matched-routing} reports paired five-seed variability and the policy-tuning protocol.",
        "Rich head / fraction & TaxScore & Cheap uncertainty & Random", main_rows, "lccc")
    (ROOT / "figures" / "routing_main.tex").write_text(routing_main, encoding="utf-8")
    rows = []
    for model in ("SeqTXCount", "ANP", "FlowLatent"):
        c = original["capacity_audit"]["crit80"][model]
        rows.append(" & ".join([model, f"{int(c['params']['mean']):,}",
                               stat(c["training_seconds"], 1),
                               interval(latency["model_ranges"][model]["batch_1"], 2),
                               interval(latency["model_ranges"][model]["batch_192"], 4)]))
    blocks.append(table(
        "tab:latency-audit",
        r"Compute audit. Training seconds are the original five-seed training segment "
        r"(mean $\pm$ standard deviation). Inference ranges are the two per-GPU mean latencies "
        r"on NVIDIA L20 with preloaded inputs, five timing trials per GPU, float32/TF32, and "
        r"64 posterior samples for ANP/Flow. Each inference entry is milliseconds per slate. "
        r"These are architecture-matched, head-only measurements, excluding score construction, "
        r"data transfer, and queueing, whose contributions require an end-to-end timing audit in the target production serving environment.",
        "Head & Parameters & Train seconds & Online ($B=1$) & Batched ($B=192$)", rows, "lrccc"))
    rows = []
    for budget in ("20pct", "30pct"):
        for head in ("ANP", "FlowLatent"):
            cells = []
            for batch in ("batch_1", "batch_192"):
                low, high = latency["routing"][batch][budget][head]["route_ms_per_slate_range"]
                digits = 2 if batch == "batch_1" else 4
                cells.append("$" + f"{low:.{digits}f}" + "$--$" + f"{high:.{digits}f}" + "$")
            savings = latency["routing"]["batch_1"][budget][head]["saving_vs_rich_everywhere_pct_range"]
            rows.append(" & ".join([head, budget.replace("pct", r"\%"), *cells,
                                   f"{savings[0]:.1f}--{savings[1]:.1f}" + r"\%"]))
    blocks.append(table(
        "tab:routing-latency",
        r"Weighted head-latency estimates derived from separate head measurements. "
        r"The calculation is $(1-r)L_{\rm cheap}+rL_{\rm rich}$, in milliseconds per slate. "
        r"Steady-state batched estimates assume each routed head can fill batches of 192. "
        r"Deployment savings additionally depend on TaxScore computation, routing overhead, and the achieved per-head batching efficiency.",
        "Rich head & Fraction & Online ms/slate & Batched ms/slate & Online saving vs. rich-only",
        rows, "lcccc"))
    (ROOT / "figures" / "control_tables.tex").write_text("\n".join(blocks), encoding="utf-8")
    print("Verified five seeds, paired advantages, and two clean latency runs. Wrote control_tables.tex.")


if __name__ == "__main__":
    main()
